// ── 묶음 ────────────────────────────────────────────────────
// 단원(3~48문제)을 5문제 안팎으로 쪼갠 것이 앱의 유일한 학습 단위다.
// 묶음 수 = 올림(문제수/5), 그 다음 고르게 분배해서 꼬리가 1~2문제로 남지 않게 한다.
//   48문제 → 10묶음 [5×8, 4×2]   26문제 → 6묶음 [5,5,4,4,4,4]
const 묶음크기 = 5;

/**
 * 챕터 이름 앞에 붙은 번호. "01 계약법 총론" → "01".
 * 화면에서 섹션을 "01 - 3"으로 적을 때 앞자리로 쓴다 (2026-08-06 사장님 지시).
 */
const 장번호 = (단원) => (단원.이름.match(/^\s*(\d+)/) || ['', ''])[1];

/** 번호를 뗀 제목. "01 계약법 총론" → "계약법 총론" */
const 장제목 = (단원) => 단원.이름.replace(/^\s*\d+\s*/, '') || 단원.이름;

function 묶음나누기(단원) {
  const 전체 = 단원.문제들;
  if (!전체.length) return [];
  const 묶음수 = Math.max(1, Math.ceil(전체.length / 묶음크기));
  const 기본 = Math.floor(전체.length / 묶음수);
  const 나머지 = 전체.length % 묶음수;
  const 번호 = 장번호(단원);
  const 제목 = 장제목(단원);

  const 결과 = [];
  let 자리 = 0;
  for (let 순번 = 0; 순번 < 묶음수; 순번++) {
    const 크기 = 기본 + (순번 < 나머지 ? 1 : 0);
    const 문제들 = 전체.slice(자리, 자리 + 크기);
    // "01 - 3" = 챕터 01의 3섹션. 챕터 번호가 없는 이름이면 챕터 이름을 그대로 쓴다.
    // **코드와 저장된 기록의 항목 이름은 그대로 '묶음'이다.** 이름까지 바꾸면 이미
    // 쌓인 기록이 안 붙으므로 화면 글자만 '섹션'으로 한다. 안드로이드도 같은 규칙.
    const 섹션이름 = `${번호 || 단원.이름} - ${순번 + 1}`;
    결과.push({
      단원,
      번호: 순번 + 1,
      총묶음: 묶음수,
      시작번호: 자리 + 1,
      끝번호: 자리 + 크기,
      문제들,
      키: `${단원키(단원)}#${순번 + 1}`,
      섹션이름,
      문제범위: 묶음수 === 1 ? `전체 ${크기}문제` : `${자리 + 1}~${자리 + 크기}번`,
      이름: `${제목} ${섹션이름}`,          // "계약법 총론 01 - 3"
      긴이름: `${단원.과목} · ${제목} ${섹션이름}`,  // "PART 3 · 계약법 · 계약법 총론 01 - 3"
    });
    자리 += 크기;
  }
  return 결과;
}

/**
 * 이 문제가 챕터에서 몇 번 문제인지 = **책에 찍힌 번호** (2026-08-06 사장님 지시).
 *
 * 문제 화면의 큰 번호를 섹션마다 01부터 새로 세면 책과 어긋나서, 책을 펴 놓고
 * 맞춰 볼 수가 없다. 19문제짜리 챕터라면 1섹션이 01~05, 2섹션은 06부터 이어진다.
 *
 * 복습 회차에는 숙달한 문제가 빠져서 자리가 밀리고 건너뛰기로 순서도 바뀌므로,
 * 순번을 따로 들고 다니지 않고 그때그때 원본 목록에서 찾는다(문제는 많아야 5개).
 * indexOf는 객체 자체를 견주므로 같은 질문이 두 번 있어도 어긋나지 않는다.
 */
function 책번호(묶, 문제) {
  const 자리 = 묶.문제들.indexOf(문제);
  return 자리 < 0 ? 묶.시작번호 : 묶.시작번호 + 자리;
}

const 단원키 = (단원) => `${단원.과목}|${단원.이름}`;

/** 문제를 가리키는 열쇠. 질문 글자를 짧은 지문으로 줄여 쓴다. */
function 문제키(단원, 문제) {
  return `${단원키(단원)}|${글자지문(문제.질문)}`;
}

// cyrb53: 짧고 충돌이 사실상 없는 문자열 해시
function 글자지문(글) {
  let ㄱ = 0xdeadbeef, ㄴ = 0x41c6ce57;
  for (let 자리 = 0; 자리 < 글.length; 자리++) {
    const 글자 = 글.charCodeAt(자리);
    ㄱ = Math.imul(ㄱ ^ 글자, 2654435761);
    ㄴ = Math.imul(ㄴ ^ 글자, 1597334677);
  }
  ㄱ = Math.imul(ㄱ ^ (ㄱ >>> 16), 2246822507) ^ Math.imul(ㄴ ^ (ㄴ >>> 13), 3266489909);
  ㄴ = Math.imul(ㄴ ^ (ㄴ >>> 16), 2246822507) ^ Math.imul(ㄱ ^ (ㄱ >>> 13), 3266489909);
  return (4294967296 * (2097151 & ㄴ) + (ㄱ >>> 0)).toString(36);
}

