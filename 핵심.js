const 숙달기준초 = 20;
const 숙달연속횟수 = 5;
const 숙달인가 = (기록) =>
  !!기록 && ((기록.최근정답 && 기록.최근걸린초 <= 숙달기준초) || 기록.연속정답 >= 숙달연속횟수);

// ── 묶음 ────────────────────────────────────────────────────
// 단원(3~48문제)을 5문제 안팎으로 쪼갠 것이 앱의 유일한 학습 단위다.
// 묶음 수 = 올림(문제수/5), 그 다음 고르게 분배해서 꼬리가 1~2문제로 남지 않게 한다.
//   48문제 → 10묶음 [5×8, 4×2]   26문제 → 6묶음 [5,5,4,4,4,4]
const 묶음크기 = 5;

/**
 * 챕터 이름 앞에 붙은 번호. "01 계약법 총론" → "01".
 * 화면에서 섹션을 "01 - 3"으로 적을 때 앞자리로 쓴다 (2026-08-06 사장님 지시).
 */
const 장번호 = (단원) => (단원.이름.match(/^\s*(\d+)/) || ['', ''])[1];

/** 번호를 뗀 제목. "01 계약법 총론" → "계약법 총론" */
const 장제목 = (단원) => 단원.이름.replace(/^\s*\d+\s*/, '') || 단원.이름;

function 묶음나누기(단원) {
  const 전체 = 단원.문제들;
  if (!전체.length) return [];
  const 묶음수 = Math.max(1, Math.ceil(전체.length / 묶음크기));
  const 기본 = Math.floor(전체.length / 묶음수);
  const 나머지 = 전체.length % 묶음수;
  const 번호 = 장번호(단원);
  const 제목 = 장제목(단원);

  const 결과 = [];
  let 자리 = 0;
  for (let 순번 = 0; 순번 < 묶음수; 순번++) {
    const 크기 = 기본 + (순번 < 나머지 ? 1 : 0);
    const 문제들 = 전체.slice(자리, 자리 + 크기);
    // "01 - 3" = 챕터 01의 3섹션. 챕터 번호가 없는 이름이면 챕터 이름을 그대로 쓴다.
    // **코드와 저장된 기록의 항목 이름은 그대로 '묶음'이다.** 이름까지 바꾸면 이미
    // 쌓인 기록이 안 붙으므로 화면 글자만 '섹션'으로 한다. 안드로이드도 같은 규칙.
    const 섹션이름 = `${번호 || 단원.이름} - ${순번 + 1}`;
    결과.push({
      단원,
      번호: 순번 + 1,
      총묶음: 묶음수,
      시작번호: 자리 + 1,
      끝번호: 자리 + 크기,
      문제들,
      키: `${단원키(단원)}#${순번 + 1}`,
      섹션이름,
      문제범위: 묶음수 === 1 ? `전체 ${크기}문제` : `${자리 + 1}~${자리 + 크기}번`,
      이름: `${제목} ${섹션이름}`,          // "계약법 총론 01 - 3"
      긴이름: `${단원.과목} · ${제목} ${섹션이름}`,  // "PART 3 · 계약법 · 계약법 총론 01 - 3"
    });
    자리 += 크기;
  }
  return 결과;
}

/**
 * 이 문제가 챕터에서 몇 번 문제인지 = **책에 찍힌 번호** (2026-08-06 사장님 지시).
 *
 * 문제 화면의 큰 번호를 섹션마다 01부터 새로 세면 책과 어긋나서, 책을 펴 놓고
 * 맞춰 볼 수가 없다. 19문제짜리 챕터라면 1섹션이 01~05, 2섹션은 06부터 이어진다.
 *
 * 복습 회차에는 숙달한 문제가 빠져서 자리가 밀리고 건너뛰기로 순서도 바뀌므로,
 * 순번을 따로 들고 다니지 않고 그때그때 원본 목록에서 찾는다(문제는 많아야 5개).
 * indexOf는 객체 자체를 견주므로 같은 질문이 두 번 있어도 어긋나지 않는다.
 */
function 책번호(묶, 문제) {
  const 자리 = 묶.문제들.indexOf(문제);
  return 자리 < 0 ? 묶.시작번호 : 묶.시작번호 + 자리;
}

const 단원키 = (단원) => `${단원.과목}|${단원.이름}`;

/**
 * 문제를 가리키는 열쇠. 질문 글자를 짧은 지문으로 줄여 쓴다.
 *
 * **안드로이드(문제기록저장소.kt)와 글자 하나까지 같아야 한다** — 과목|목차|sha256(질문)[:16].
 * 2026-09-10까지 웹은 다른 해시(cyrb53)를 써서, 폰과 웹의 문제기록·오답노트가 같은 문제인데
 * 다른 열쇠로 따로 쌓였다(숙달 여부가 기기 사이에 안 넘어가고 오답노트 수가 두 배로 보였다).
 * 옛 열쇠로 쌓인 기록은 저장소.옛키이전()이 한 번 옮긴다.
 */
function 문제키(단원, 문제) {
  return `${단원키(단원)}|${글자지문(문제.질문)}`;
}

/** sha256 앞 16자(8바이트). 안드로이드 문제기록저장소.문제키와 같은 자리수다. */
function 글자지문(글) {
  return sha256(String(글).trim()).slice(0, 16);
}

/**
 * SHA-256 (동기). 브라우저의 crypto.subtle은 비동기라, 화면을 그리는 도중 곳곳에서
 * 바로 값을 받아 써야 하는 문제키에는 쓸 수 없어서 직접 구현했다.
 * 표준 상수를 그대로 적었다(계산해 내면 부동소수 오차로 끝자리가 틀릴 수 있다).
 * tests/웹문제키.test.js 가 node의 crypto와 결과가 같은지 확인한다.
 */
const SHA256_K = [
  0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
  0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
  0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
  0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
  0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
  0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
  0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
  0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
];
function sha256(글) {
  const 바이트 = new TextEncoder().encode(글);
  const 블록수 = (바이트.length + 9 + 63) >> 6;
  const 버퍼 = new Uint8Array(블록수 * 64);
  버퍼.set(바이트);
  버퍼[바이트.length] = 0x80;
  const 보기 = new DataView(버퍼.buffer);
  const 길이비트 = 바이트.length * 8;
  보기.setUint32(버퍼.length - 8, Math.floor(길이비트 / 0x100000000));
  보기.setUint32(버퍼.length - 4, 길이비트 >>> 0);

  const 돌리기 = (x, n) => (x >>> n) | (x << (32 - n));
  const H = [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19];
  const W = new Uint32Array(64);
  for (let 자리 = 0; 자리 < 버퍼.length; 자리 += 64) {
    for (let t = 0; t < 16; t++) W[t] = 보기.getUint32(자리 + t * 4);
    for (let t = 16; t < 64; t++) {
      const s0 = 돌리기(W[t - 15], 7) ^ 돌리기(W[t - 15], 18) ^ (W[t - 15] >>> 3);
      const s1 = 돌리기(W[t - 2], 17) ^ 돌리기(W[t - 2], 19) ^ (W[t - 2] >>> 10);
      W[t] = (W[t - 16] + s0 + W[t - 7] + s1) >>> 0;
    }
    let [a, b, c, d, e, f, g, h] = H;
    for (let t = 0; t < 64; t++) {
      const S1 = 돌리기(e, 6) ^ 돌리기(e, 11) ^ 돌리기(e, 25);
      const ch = (e & f) ^ (~e & g);
      const t1 = (h + S1 + ch + SHA256_K[t] + W[t]) >>> 0;
      const S0 = 돌리기(a, 2) ^ 돌리기(a, 13) ^ 돌리기(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + maj) >>> 0;
      h = g; g = f; f = e; e = (d + t1) >>> 0;
      d = c; c = b; b = a; a = (t1 + t2) >>> 0;
    }
    H[0] = (H[0] + a) >>> 0; H[1] = (H[1] + b) >>> 0; H[2] = (H[2] + c) >>> 0; H[3] = (H[3] + d) >>> 0;
    H[4] = (H[4] + e) >>> 0; H[5] = (H[5] + f) >>> 0; H[6] = (H[6] + g) >>> 0; H[7] = (H[7] + h) >>> 0;
  }
  return H.map((x) => x.toString(16).padStart(8, '0')).join('');
}

// cyrb53: 2026-09-10까지 문제키에 쓰던 해시. **옛 기록을 새 열쇠로 옮길 때만** 쓴다.
function 옛글자지문(글) {
  let ㄱ = 0xdeadbeef, ㄴ = 0x41c6ce57;
  for (let 자리 = 0; 자리 < 글.length; 자리++) {
    const 글자 = 글.charCodeAt(자리);
    ㄱ = Math.imul(ㄱ ^ 글자, 2654435761);
    ㄴ = Math.imul(ㄴ ^ 글자, 1597334677);
  }
  ㄱ = Math.imul(ㄱ ^ (ㄱ >>> 16), 2246822507) ^ Math.imul(ㄴ ^ (ㄴ >>> 13), 3266489909);
  ㄴ = Math.imul(ㄴ ^ (ㄴ >>> 16), 2246822507) ^ Math.imul(ㄱ ^ (ㄱ >>> 13), 3266489909);
  return (4294967296 * (2097151 & ㄴ) + (ㄱ >>> 0)).toString(36);
}

