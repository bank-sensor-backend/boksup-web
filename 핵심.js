function 읽기(키, 기본값) {
  try {
    const 글 = localStorage.getItem(키);
    return 글 ? JSON.parse(글) : 기본값;
  } catch (오류) {
    console.warn('저장된 내용을 읽지 못했습니다', 키, 오류);
    return 기본값;
  }
}

function 쓰기(키, 값) {
  try {
    localStorage.setItem(키, JSON.stringify(값));
  } catch (오류) {
    alert('저장 공간이 부족해 기록을 저장하지 못했습니다.');
    console.error(오류);
  }
}

