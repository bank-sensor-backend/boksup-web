/** 오늘부터 며칠 뒤 자정 (밀리초) */
function 자정밀리(며칠뒤 = 0) {
  const 날 = new Date();
  날.setHours(0, 0, 0, 0);
  날.setDate(날.getDate() + 며칠뒤);
  return 날.getTime();
}

/** 오늘부터 며칠 뒤 아침 9시 */
function 아침9시밀리(일수) {
  const 날 = new Date();
  날.setHours(9, 0, 0, 0);
  날.setDate(날.getDate() + 일수);
  return 날.getTime();
}

const 하루밀리 = 24 * 3600 * 1000;
const 날수차이 = (부터밀리, 까지밀리) =>
  Math.round((자정에맞추기(까지밀리) - 자정에맞추기(부터밀리)) / 하루밀리);

