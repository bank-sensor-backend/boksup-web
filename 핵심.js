// ── 점수 ────────────────────────────────────────────────────
// 2026-08-06 사장님 지시로 바뀐 배점. 100점 만점 기준.
//
// 90초 안에 **맞힌** 경우 (구간마다 딱 떨어지는 점수):
//   ~30초 90점 · 31~40초 80점 · 41~50초 70점 · 51~60초 60점
//   61~70초 50점 · 71~80초 40점 · 81~90초 30점
// 90초 안에 틀리면 0점. (틀린 걸 늦게 낸다고 더 깎으면 앞뒤가 안 맞으므로)
//
// 90초를 넘기면 맞든 틀리든 감점. 10초마다 10점씩 더 깎고 -100점에서 멈춘다.
//   91~100초 -10 · 101~110초 -20 · 111~120초 -30 · … · 181초~ -100
// 90초를 넘겼어도 정답이면 그 감점에서 +10점.
const 점수규칙 = {
  제한초: 90,
  구간들: [
    [30, 90], [40, 80], [50, 70], [60, 60], [70, 50], [80, 40], [90, 30],
  ],
  오답점수: 0,
  감점단위초: 10,
  감점단위점: 10,
  최저점: -100,
  정답보정: 10,
};

function 문제점수(맞음, 걸린초) {
  const 초 = Math.max(0, Math.floor(걸린초));
  if (초 <= 점수규칙.제한초) {
    if (!맞음) return 점수규칙.오답점수;
    const 칸 = 점수규칙.구간들.find(([끝]) => 초 <= 끝);
    return 칸 ? 칸[1] : 점수규칙.구간들[점수규칙.구간들.length - 1][1];
  }
  const 단계 = Math.ceil((초 - 점수규칙.제한초) / 점수규칙.감점단위초);
  const 감점 = Math.max(점수규칙.최저점, -점수규칙.감점단위점 * 단계);
  return 감점 + (맞음 ? 점수규칙.정답보정 : 0);
}

/** 한 회분의 평균점수 = 문제별 점수의 평균 */
function 평균점수계산(결과들) {
  if (!결과들.length) return 0;
  const 합 = 결과들.reduce((누적, ㄱ) => 누적 + 문제점수(ㄱ.맞음, ㄱ.걸린초), 0);
  return Math.round(합 / 결과들.length);
}

