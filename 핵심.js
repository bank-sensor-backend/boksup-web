const 하루밀리 = 24 * 3600 * 1000;
const 날수차이 = (부터밀리, 까지밀리) =>
  Math.round((자정에맞추기(까지밀리) - 자정에맞추기(부터밀리)) / 하루밀리);

function 자정에맞추기(밀리) {
  const 날 = new Date(밀리);
  날.setHours(0, 0, 0, 0);
  return 날.getTime();
}

// ── 오늘 할 일 계산 ──────────────────────────────────────────
// 오늘 할 일 = 오늘 복습할 묶음 + 오늘 나갈 새 묶음. 복습이 먼저다.
/**
 * 1회독 현황과 오늘 할 일.
 *
 * 인자로 받는 것은 **진도묶음**(합격서 빈칸을 뺀 것)이다. 빈칸은 890문제가 넘는
 * 연습이라 1회독에 넣으면 하루 목표가 세 배로 뛰고 [오늘 할 일]이 빈칸으로
 * 덮인다. 다만 복습 일정은 빈칸도 문제집과 똑같이 챙기므로, 복습 묶음을 찾을 때만
 * 전체묶음에서 찾는다. **안드로이드(학습계획저장소.현황)와 규칙이 같아야 한다.**
 */
function 현황계산(진도묶음, 전체묶음 = 진도묶음) {
  const 계 = 저장소.계획();
  const 문제이력 = 저장소.문제기록전체();
  const 시작밀리 = 계?.회독시작밀리 ?? 0;
  const 오늘0시 = 자정밀리();

  const 마지막밀리 = (묶) =>
    묶.문제들.reduce(
      (최대, 문제) => Math.max(최대, 문제이력[문제키(묶.단원, 문제)]?.마지막밀리 ?? 0),
      0
    );

  let 푼묶음수 = 0;
  let 오늘푼새묶음 = 0;
  const 안푼묶음들 = [];
  진도묶음.forEach((묶, 차례) => {
    const 마지막 = 마지막밀리(묶);
    if (마지막 > 0 && 마지막 >= 시작밀리) {
      푼묶음수++;
      if (마지막 >= 오늘0시) 오늘푼새묶음++;
    } else {
      안푼묶음들.push({ 묶, 차례 });
    }
  });
  const 남은묶음수 = 안푼묶음들.length;

  // 새 진도는 사장님이 고른 지점부터 나간다. 끝까지 가면 앞쪽으로 돌아온다.
  // (2026-08-06 요청: 늘 '01 권리의 변동'부터 강제되던 걸 없앰)
  const 시작차례 = Math.max(0, 진도묶음.findIndex((묶) => 묶.키 === 계?.시작묶음키));
  const 전체수 = 진도묶음.length || 1;
  안푼묶음들.sort(
    (ㄱ, ㄴ) =>
      ((ㄱ.차례 - 시작차례 + 전체수) % 전체수) - ((ㄴ.차례 - 시작차례 + 전체수) % 전체수)
  );

  const 남은일수 = 계 ? Math.max(1, 날수차이(Date.now(), 계.목표일밀리) + 1) : 0;
  const 목표지남 = !!계 && 자정에맞추기(계.목표일밀리) < 오늘0시;

  // 하루 목표는 '오늘 아침에 남아 있던 수' 기준. 오늘 몇 개를 풀든 목표가 줄지 않는다.
  const 오늘시작남은 = 남은묶음수 + 오늘푼새묶음;
  const 오늘새목표 = !계 || 오늘시작남은 === 0
    ? 0
    : Math.max(1, Math.ceil(오늘시작남은 / 남은일수));

  const 묶음찾기 = new Map(전체묶음.map((묶) => [묶.키, 묶]));
  const 복습할일들 = 저장소.오늘복습일정()
    .map((일정) => {
      const 묶 = 묶음찾기.get(일정.묶음키);
      if (!묶) return null;
      return 미숙달문제들(묶).length ? { 묶, 복습회차: 일정.회차 } : null;
    })
    .filter(Boolean);

  const 새몫 = Math.min(남은묶음수, Math.max(0, 오늘새목표 - 오늘푼새묶음));
  const 새할일들 = 안푼묶음들.slice(0, 새몫).map(({ 묶 }) => ({ 묶, 복습회차: null }));

  const 오늘할일들 = [...복습할일들, ...새할일들];
  return {
    계획: 계,
    전체묶음수: 진도묶음.length,
    전체문제수: 진도묶음.reduce((합, 묶) => 합 + 묶.문제들.length, 0),
    푼묶음수,
    남은묶음수,
    남은일수,
    오늘새목표,
    오늘푼새묶음,
    복습할일들,
    새할일들,
    오늘할일들,
    오늘문제수: 오늘할일들.reduce((합, ㄱ) => 합 + ㄱ.묶.문제들.length, 0),
    목표지남,
    진행률: 진도묶음.length ? Math.floor((푼묶음수 * 100) / 진도묶음.length) : 0,
    회독끝: 진도묶음.length > 0 && 남은묶음수 === 0,
  };
}

/** 아직 복습이 필요한 문제들 (문제집 순서 그대로) */
function 미숙달문제들(묶) {
  const 이력 = 저장소.문제기록전체();
  return 묶.문제들.filter((문제) => !숙달인가(이력[문제키(묶.단원, 문제)]));
}

/**
 * 첫 화면에 띄우는 리포트 (2026-08-06 사장님 요청).
 * "이번 주에 뭘 복습해야 하나 · 어디가 약한가"를 한 자리에서 본다.
 *
 * 이번주: 오늘부터 7일 안에 예정된 복습을 날짜별로 묶는다. 이미 날짜가 지난
 * 일정은 오늘 칸으로 몰아 준다(어제 몫이 따로 서 있으면 밀린 느낌만 준다).
 * 취약: 푼 적이 있는 섹션 중 평균점수가 낮은 다섯 개. 점수가 없으면 못 고른다.
 */
function 리포트계산(전체묶음) {
  const 오늘0시 = 자정밀리();
  const 이레뒤 = 자정밀리(7);
  const 찾기 = new Map(전체묶음.map((묶) => [묶.키, 묶]));

  const 날짜별 = new Map();
  저장소.남은일정().forEach((일정) => {
    if (일정.예정밀리 >= 이레뒤) return;
    const 묶 = 찾기.get(일정.묶음키);
    if (!묶) return;
    const 남은 = 미숙달문제들(묶).length;
    if (!남은) return;   // 다 숙달한 섹션은 더 낼 게 없다
    const 날 = Math.max(오늘0시, 자정에맞추기(일정.예정밀리));
    const 칸 = 날짜별.get(날) || [];
    칸.push({ 묶, 회차: 일정.회차, 남은, 지남: 일정.예정밀리 < 오늘0시 });
    날짜별.set(날, 칸);
  });
  const 이번주 = [...날짜별.entries()]
    .sort((ㄱ, ㄴ) => ㄱ[0] - ㄴ[0])
    .map(([날, 것들]) => ({ 날, 것들 }));

  const 취약 = 전체묶음
    .map((묶) => {
      const 기록들 = 저장소.회차별기록(묶.키);
      const 점수들 = 기록들
        .map((ㄱ) => ㄱ.평균점수)
        .filter((ㄱ) => ㄱ !== null && ㄱ !== undefined && !Number.isNaN(ㄱ));
      if (!점수들.length) return null;
      return {
        묶,
        평균: Math.round(점수들.reduce((ㄱ, ㄴ) => ㄱ + ㄴ, 0) / 점수들.length),
        회차수: 기록들.length,
        남은문제: 미숙달문제들(묶).length,
        마지막밀리: Math.max(...기록들.map((ㄱ) => ㄱ.일시밀리)),
      };
    })
    .filter(Boolean)
    .sort((ㄱ, ㄴ) => ㄱ.평균 - ㄴ.평균 || ㄴ.남은문제 - ㄱ.남은문제)
    .slice(0, 5);

  return {
    이번주,
    취약,
    이번주섹션수: 이번주.reduce((합, ㄱ) => 합 + ㄱ.것들.length, 0),
    오답수: Object.keys(저장소.오답노트()).length,
  };
}

