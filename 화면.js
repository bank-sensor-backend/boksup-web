/** 섹션 하나를 푼다 */
function 풀기화면(순번글) {
  const 묶 = 전체묶음[Number(순번글)];
  if (!묶) return 이동('집');

  // 복습이면 아직 숙달하지 않은 문제만 낸다.
  // 다 숙달했는데도 직접 눌러 들어온 경우엔 전체를 다시 푼다(추가 연습).
  const 처음인가 = 저장소.완주횟수(묶.키) === 0;
  const 남은문제들 = 미숙달문제들(묶);
  const 낼문제들 = 처음인가 || !남은문제들.length ? 묶.문제들 : 남은문제들;

  풀이시작({
    묶,
    안내: `${묶.섹션이름} (${묶.문제범위})`,
    낼것들: 낼문제들.map((문제) => ({ 단원: 묶.단원, 문제, 번호: 책번호(묶, 문제) })),
  });
}

/**
 * 오답노트에 담아 둔 문제만 몰아서 푼다 (2026-08-06 사장님 요청).
 * 섹션 완주 기록과 복습 일정은 건드리지 않는다. 여러 챕터가 섞이므로
 * 문제마다 어느 챕터 것인지 함께 들고 다닌다.
 */
function 오답풀기화면() {
  const 것들 = 오답문제들();
  if (!것들.length) return 이동('오답');
  풀이시작({
    묶: null,
    안내: `오답노트 ${것들.length}문제 — 맞히면 노트에서 빠집니다`,
    낼것들: 것들.map(({ 단원, 문제, 번호 }) => ({ 단원, 문제, 번호 })),
  });
}

function 풀이시작({ 묶, 안내, 낼것들 }) {
  풀이 = {
    묶,                                   // 오답노트 연습이면 null
    안내,
    낼것들: [...낼것들],                   // [{단원, 문제, 번호}]
    이전이력: 저장소.문제기록전체(),
    현재번호: 0,
    정답수: 0,
    오답번호들: [],
    결과들: 낼것들.map(() => null),
    쌓인초들: 낼것들.map(() => 0),          // 건너뛴 문제가 쓴 시간을 모아 둔다
    넘긴적: 낼것들.map(() => false),
    // 종이에 볼펜으로 표시하듯 보기마다 O/X를 적어 둔다 (2026-08-06 사장님 요청)
    표시들: 낼것들.map(({ 문제 }) => 문제.보기.map(() => '')),
    고른순번: -1,   // 답으로 낸 보기 (-1이면 아직)
    찍은순번: -1,   // 한 번 눌러 골라 둔 보기. 한 번 더 눌러야 답으로 나간다
    누적밀리: 0,
    구간시작: Date.now(),
    문제시작밀리: 0,
    마무리됨: false,
    // 점수를 매기지 않는 연습(합격서 빈칸)인가 (2026-08-08 사장님 지시).
    // 오답노트 연습은 여러 과목이 섞이므로 '전부 연습일 때만' 연습으로 본다.
    연습인가: 낼것들.length > 0 && 낼것들.every(({ 단원 }) => 단원.연습),
  };
  문제그리기();
  시계시작();
}

const 지금것 = () => 풀이.낼것들[풀이.현재번호];

function 경과밀리() {
  return 풀이.누적밀리 + (풀이.구간시작 ? Date.now() - 풀이.구간시작 : 0);
}

/**
 * 이 문제에 쓴 초. **답을 고른 뒤에는 그때 잰 값에서 멈춘다** (2026-08-06 사장님 지적).
 * 점수는 처음부터 답을 고른 순간의 초로 매겨졌지만 화면 시계만 계속 올라가서,
 * 해설을 읽는 동안 숫자가 늘어 점수와 어긋나 보였다.
 */
const 이번문제초 = () => {
  const 굳은 = 풀이.결과들[풀이.현재번호];
  if (굳은) return 굳은.걸린초;
  return Math.floor((경과밀리() - 풀이.문제시작밀리) / 1000);
};

let 시계표 = null;
function 시계시작() {
  clearInterval(시계표);
  시계표 = setInterval(시계그리기, 250);
}
function 시계멈춤() {
  clearInterval(시계표);
  시계표 = null;
}

// 화면을 벗어나면 시계를 멈춘다 (전화 오면 억울하지 않게)
document.addEventListener('visibilitychange', () => {
  if (!풀이 || 풀이.마무리됨) return;
  if (document.hidden) {
    풀이.누적밀리 = 경과밀리();
    풀이.구간시작 = 0;
    시계멈춤();
  } else {
    풀이.구간시작 = Date.now();
    시계시작();
  }
});

