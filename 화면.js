/**
 * 보기 한 줄 = 보기 글 + 오른쪽에 O / X 칸 (2026-08-06 사장님 요청).
 *
 * 종이에 볼펜으로 풀 때처럼 보기마다 맞다/틀리다를 스스로 표시해 두는 칸이다.
 * **채점과는 상관없다.** 답은 보기 글을 눌러서 낸다.
 */
function 보기들HTML() {
  const { 문제 } = 지금것();
  const 표시 = 풀이.표시들[풀이.현재번호];
  const 낸뒤 = 풀이.고른순번 >= 0;

  return 문제.보기.map((글, 순번) => {
    const 칠 = !낸뒤 ? (순번 === 풀이.찍은순번 ? '찍음' : '')
      : 순번 + 1 === 문제.정답 ? '정답'
      : 순번 === 풀이.고른순번 ? '오답' : '';
    return `<li class="보기줄">
      <button class="보기 ${칠}" data-순번="${순번}" ${낸뒤 ? 'disabled' : ''}>
        <span class="보기번호">${번호표[순번] || 순번 + 1}</span>
        <span class="보기글">${안전글(글)}</span>
      </button>
      <span class="표시칸">
        <button class="표시 동그라미 ${표시[순번] === 'O' ? '켬' : ''}"
                data-표시="O" data-순번="${순번}" ${낸뒤 ? 'disabled' : ''}>O</button>
        <button class="표시 엑스 ${표시[순번] === 'X' ? '켬' : ''}"
                data-표시="X" data-순번="${순번}" ${낸뒤 ? 'disabled' : ''}>X</button>
      </span>
    </li>`;
  }).join('');
}

function 누름안내글() {
  if (풀이.고른순번 >= 0) return '';
  const { 문제 } = 지금것();
  if (풀이.찍은순번 < 0) {
    return 'O · X 는 스스로 표시해 두는 칸입니다. 답은 보기를 눌러서 냅니다.';
  }
  return `${번호표[풀이.찍은순번] || 풀이.찍은순번 + 1}번을 골랐습니다 —
    한 번 더 누르면 이 답으로 냅니다`;
}

/** 보기 목록만 다시 그린다 (시계와 문제 글은 그대로 두려고 따로 뺐다) */
function 보기다시그리기() {
  const 목록 = document.getElementById('보기목록');
  const 안내 = document.getElementById('누름안내');
  if (목록) 목록.innerHTML = 보기들HTML();
  if (안내) 안내.innerHTML = 누름안내글();
  보기단추붙이기();
}

function 보기단추붙이기() {
  document.querySelectorAll('#보기목록 .보기').forEach((단추) => {
    단추.addEventListener('click', () => 보기누름(Number(단추.dataset.순번)));
  });
  document.querySelectorAll('#보기목록 .표시').forEach((단추) => {
    단추.addEventListener('click', () =>
      표시누름(Number(단추.dataset.순번), 단추.dataset.표시));
  });
}

/**
 * 보기를 누르면 먼저 '골라 둔' 상태가 되고, **같은 보기를 한 번 더** 눌러야
 * 답으로 나간다 (2026-08-06 사장님 요청: 잘못 눌러 바로 채점되는 걸 막는다).
 */
function 보기누름(순번) {
  if (풀이.고른순번 >= 0) return;
  if (풀이.찍은순번 === 순번) {
    답고르기(순번);
    return;
  }
  풀이.찍은순번 = 순번;
  보기다시그리기();
}

/** O / X 는 스스로 표시해 두는 칸이라 채점과 상관없다. 같은 걸 또 누르면 지워진다. */
function 표시누름(순번, 무엇) {
  if (풀이.고른순번 >= 0) return;
  const 표시 = 풀이.표시들[풀이.현재번호];
  표시[순번] = 표시[순번] === 무엇 ? '' : 무엇;
  보기다시그리기();
}

/**
 * 출처 머리글 — "합격서 p42 · POINT 06 법률행위의 부관" (2026-08-08 사장님 요청).
 *
 * 예전에는 발문 끝에 "(합격서 p42)"를 붙여서 문제 글에 섞였다. 어디서 나온
 * 내용인지는 **풀기 전에 먼저** 눈에 들어와야 해서 발문 위로 올렸다.
 * 눌러 보면 그 쪽을 바로 펼친다(해설을 볼 때까지 기다릴 필요가 없다).
 * **안드로이드(QuizActivity.출처머리그리기)와 내용이 같아야 한다.**
 */
function 출처머리HTML(문제) {
  if (!문제.출처) return '';
  const 펼칠수있나 = 문제.출처쪽 > 0 && 합격서쪽있나(문제.출처쪽);
  const 글 = `📗 ${안전글(문제.출처)}`;
  if (!펼칠수있나) return `<p class="출처머리">${글}</p>`;
  return `<a class="출처머리 눌림" href="#${합격서쪽주소(문제.출처쪽)}">${글}
    <span class="흐림">› 눌러서 펼치기</span></a>`;
}

/**
 * 질문 글을 문제집 지면처럼 나눠 그린다.
 * 문제집은 발문 아래에 ㉠㉡㉢ 지문을 네모 상자로 따로 싣는데, 우리 자료도
 * 발문 다음에 빈 줄을 두고 지문이 이어지는 형태라 그대로 갈라 쓸 수 있다.
 */
function 질문HTML(질문) {
  const 조각 = 질문.split(/\n\s*\n/);
  const 발문 = 조각[0];
  const 지문 = 조각.slice(1).join('\n').trim();

  // "(36회)", "(28회 수정)", "(36회 대표기출)" 같은 회차 표시는 문제집처럼 오른쪽에 작게
  const 회차맞음 = 발문.match(/\s*\(([^()]*\d+회[^()]*)\)\s*$/);
  const 본문 = 회차맞음 ? 발문.slice(0, 회차맞음.index).trim() : 발문.trim();
  const 회차 = 회차맞음 ? 회차맞음[1] : '';

  return `
    <p class="발문">${강조HTML(본문)}</p>
    ${회차 ? `<p class="회차">• ${안전글(회차)}</p>` : ''}
    ${지문 ? `<div class="지문상자">${안전글(지문).replace(/\n/g, '<br>')}</div>` : ''}
  `;
}

/**
 * 문제집은 발문에서 '틀린 / 옳은 / 아닌' 같은 판단 낱말만 굵게+밑줄로 찍는다.
 * 그 낱말을 놓쳐서 틀리는 일이 많아서다. 똑같이 그 낱말만 강조한다.
 */
function 강조HTML(글) {
  return 안전글(글).replace(
    /(옳지 않은|틀린|옳은|아닌|모두 고른)/g,
    '<strong>$1</strong>'
  );
}
function 답고르기(누른순번) {
  if (풀이.고른순번 >= 0) return;
  const { 현재번호 } = 풀이;
  const { 단원, 문제 } = 지금것();
  const 걸린초 = 이번문제초();
  const 맞음 = 누른순번 + 1 === 문제.정답;

  풀이.고른순번 = 누른순번;
  풀이.결과들[현재번호] = { 단원, 문제, 맞음, 걸린초, 고른순번: 누른순번 };
  if (맞음) 풀이.정답수++;
  else 풀이.오답번호들.push(지금것().번호);

  // 틀린 문제는 묻지 않고 오답노트에 담는다 (2026-08-06 사장님 요청).
  // 맞은 문제도 아래 단추로 담을 수 있다.
  if (!맞음) 저장소.오답담기(단원, 문제, true);

  보기다시그리기();
  const 넘김칸 = document.getElementById('넘김칸');
  if (넘김칸) 넘김칸.innerHTML = '';   // 답을 냈으면 건너뛰기는 감춘다

  // 연습(합격서 빈칸)은 점수를 매기지 않는다. 대신 걸린 시간만 적는다.
  const 점수말조각 = 풀이.연습인가 ? `${걸린초}초` : `${문제점수(맞음, 걸린초)}점`;
  document.getElementById('해설칸').innerHTML = `
    <div class="판정 ${맞음 ? '초록' : '빨강'}">
      ${맞음 ? '⭕ 정답!' : `❌ 오답 — 정답은 ${번호표[문제.정답 - 1] || 문제.정답}`}
      ${점수말조각} <span class="흐림">${안전글(숙달안내(단원, 문제, 맞음, 걸린초))}</span>
    </div>
    <div class="해설">${안전글(문제.해설 || '(해설 없음)').replace(/\n/g, '<br>')}</div>
    ${합격서단추HTML(단원)}
    <button class="선단추 담기단추" id="담기단추"></button>
    <button class="찬단추" id="다음단추">
      ${현재번호 === 풀이.낼것들.length - 1 ? '결과 보기' : '다음 문제'}
    </button>
  `;
  담기단추그리기();
  document.getElementById('다음단추').addEventListener('click', 다음으로);
  document.getElementById('해설칸').scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}

