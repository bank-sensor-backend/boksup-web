let 마지막결과 = null;

function 마무리() {
  if (풀이.마무리됨) return;   // 두 번 눌러도 기록이 두 번 저장되지 않게
  풀이.마무리됨 = true;
  시계멈춤();

  const { 묶, 결과들, 정답수, 오답번호들, 연습인가 } = 풀이;
  const 걸린초 = Math.floor(경과밀리() / 1000);
  // 연습(합격서 빈칸)은 점수를 매기지 않는다 (2026-08-08 사장님 지시).
  // 값 없음(null)으로 넣어 두면 화면에는 "—점"으로 나오고
  // 리포트의 '점수가 낮은 섹션' 순위에도 섞이지 않는다.
  const 평균 = 연습인가 ? null : 평균점수계산(결과들);

  // 문제별 정답·시간 반영은 어느 쪽이든 한다. 오답노트 연습도 실력은 실력이다.
  // 여러 챕터가 섞일 수 있으므로 챕터별로 나눠 넣는다.
  const 챕터별 = new Map();
  결과들.forEach((ㄱ) => {
    const 칸 = 챕터별.get(ㄱ.단원) || [];
    칸.push(ㄱ);
    챕터별.set(ㄱ.단원, 칸);
  });
  챕터별.forEach((것들, 단원) => 저장소.결과반영(단원, 것들));

  const 푼내용 = 결과들.map((ㄱ, 자리) => ({
    단원: ㄱ.단원,
    문제: ㄱ.문제,
    번호: 풀이.낼것들[자리].번호,
    맞음: ㄱ.맞음,
    걸린초: ㄱ.걸린초,
    고른순번: ㄱ.고른순번,
  }));

  if (!묶) {
    // 오답노트 연습: 섹션 완주 기록도 복습 일정도 건드리지 않는다.
    // 맞힌 문제는 노트에서 뺀다(그러라고 담아 둔 것이다).
    결과들.filter((ㄱ) => ㄱ.맞음).forEach((ㄱ) => 저장소.오답빼기(문제키(ㄱ.단원, ㄱ.문제)));
    마지막결과 = {
      연습: true, 무점수: 연습인가, 묶음키: null, 걸린초, 문제수: 결과들.length, 정답수,
      평균, 회차: 0, 남은수: 0, 오답번호들, 푼내용,
    };
    풀이 = null;
    저절로맞추기();
    return 이동('결과');
  }

  const 처음인가 = 저장소.완주횟수(묶.키) === 0;
  // 복습 회차는 '완주 횟수'가 아니라 복습 일정표를 보고 정한다
  const 복습회차 = 처음인가 ? null : 저장소.이번복습회차(묶.키);
  const 기록회차 = 처음인가 ? 1 : 복습회차 ?? 0;
  const 남은수 = 미숙달문제들(묶).length;

  저장소.기록추가({
    묶음키: 묶.키,
    과목: 묶.단원.과목,
    목차이름: 묶.단원.이름,
    묶음이름: 묶.섹션이름,
    일시밀리: Date.now(),
    걸린초,
    문제수: 결과들.length,
    정답수,
    회차: 기록회차,
    평균점수: 평균,
  });
  if (처음인가) 저장소.일정만들기(묶);
  else if (복습회차) 저장소.일정완료표시(묶.키, 복습회차);
  // 전부 숙달했으면 남은 일정을 지운다(다시 내 봐야 볼 문제가 없다)
  if (남은수 === 0) 저장소.일정삭제(묶.키);

  마지막결과 = {
    연습: false, 무점수: 연습인가, 묶음키: 묶.키, 걸린초, 문제수: 결과들.length, 정답수,
    평균, 회차: 기록회차, 남은수, 오답번호들, 푼내용,
  };
  풀이 = null;
  이동('결과');
  // 섹션을 마쳤으니 이때 맞춘다(문제를 푸는 중이 아니라 안전한 시점이다)
  저절로맞추기();
}

