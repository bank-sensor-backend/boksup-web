const 문제시계말 = (초) => (초 < 60 ? `${초}초` : 시계말(초));

// 시계는 문제마다 0초부터 다시 잰다. 섹션 전체 시간은 결과 화면에서만 본다
// (2026-08-06 사장님 지시: 이어서 재면 지금 이 문제에 몇 초 썼는지 알 수 없다)
